#!/usr/bin/env python3
"""
DeveloperOS Multi-Target Design System Adapter Compiler
Compiles canonical tokens.json into platform-specific adapters:
- CSS Custom Properties (dist/css/tokens.css)
- TypeScript / React Tokens (dist/react/tokens.ts)
- Streamlit Native Theme & Scoped Styles (dist/streamlit/theme.toml & devos_theme.py)
- Chrome Extension Styles (dist/extension/tokens.css)
"""

import json
import sys
from pathlib import Path

SYSTEM_ROOT = Path(__file__).resolve().parent.parent
TOKENS_PATH = SYSTEM_ROOT / "tokens.json"
DIST_DIR = SYSTEM_ROOT / "dist"


def resolve_val(token_obj: dict) -> str:
    """Returns the resolved value or fallback if placeholder."""
    val = token_obj.get("$value", "")
    if isinstance(val, str) and val.startswith("__PLACEHOLDER_"):
        return token_obj.get("fallback", val)
    return str(val)


